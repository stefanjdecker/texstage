"""Render the illustrated manual from docs/manual-content.json.

Install requirements/docs.txt. By default writes docs/manual.md and docs/manual.pdf.
--check verifies generated Markdown and screenshot hashes without changing files.
--output-dir writes both reading formats elsewhere for a preview or CI check.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"


def slug(text):
    return re.sub(r"[^a-z0-9 -]", "", text.lower()).replace(" ", "-")


def markdown(data):
    lines = ["<!-- Generated by maintenance/build_manual.py from manual-content.json. -->",
             "# " + data["title"], "", "**" + data["subtitle"] + "**", "",
             "[Download the illustrated PDF](manual.pdf)", "", "## Contents", ""]
    lines += [f"- [{p['title']}](#{slug(p['title'])})" for p in data["pages"][1:]]
    for index, page in enumerate(data["pages"]):
        if index:
            lines += ["", "## " + page["title"], ""]
        for block in page["blocks"]:
            if "p" in block:
                lines += [block["p"], ""]
            elif "heading" in block:
                lines += ["### " + block["heading"], ""]
            elif "bullets" in block:
                lines += ["- " + line for line in block["bullets"]] + [""]
            elif "code" in block:
                lines += ["```", block["code"], "```", ""]
            elif "table" in block:
                table = block["table"]
                lines += ["| " + " | ".join(table["headers"]) + " |",
                          "| " + " | ".join("---" for _ in table["headers"]) + " |"]
                lines += ["| " + " | ".join(row) + " |" for row in table["rows"]]
                lines += [""]
        for picture in page["images"]:
            lines += [f"![{picture['caption']}]({picture['file']})", "", picture["caption"], ""]
    return "\n".join(lines).rstrip() + "\n"


def check_images(data):
    manifest = json.loads((DOCS / "images/manual/captures.json").read_text(encoding="utf-8"))
    hashes = {p["file"]: p["sha256"] for p in manifest["screenshots"]}
    used = {p["file"] for page in data["pages"] for p in page["images"]}
    assert used == set(hashes), "Manual images and capture inventory differ"
    for filename in used:
        path = (DOCS / filename).resolve()
        assert path.is_relative_to(DOCS.resolve())
        assert hashlib.sha256(path.read_bytes()).hexdigest() == hashes[filename], filename


def build_manifest(output_dir):
    inputs = ["docs/manual-content.json", "docs/images/manual/captures.json",
              "maintenance/build_manual.py"]
    return {
        "schema_version": 1,
        "inputs": {name: hashlib.sha256((ROOT/name).read_bytes()).hexdigest() for name in inputs},
        "outputs": {name: hashlib.sha256((output_dir/name).read_bytes()).hexdigest()
                    for name in ("manual.md", "manual.pdf")},
    }


def render_pdf(data, target):
    # Optional dependencies stay out of runtime and the offline --check path.
    from reportlab.pdfgen import canvas
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.utils import ImageReader
    from reportlab.platypus import Paragraph, Table, TableStyle
    from reportlab.lib.units import mm

    width, height = landscape(A4)
    margin = 16 * mm
    usable = width - margin * 2
    purple = colors.HexColor("#46178F")
    ink = colors.HexColor("#172539")
    muted = colors.HexColor("#596577")
    pale = colors.HexColor("#F2F0F7")
    c = canvas.Canvas(str(target), pagesize=(width, height), pageCompression=1, invariant=1)
    c.setTitle(data["title"])
    c.setAuthor("texstage project")
    c.setSubject("Illustrated presenter and participant guide")

    def rich(text):
        text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r"\1", text)
        text = escape(text)
        text = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", text)
        text = re.sub(r"`([^`]+)`", r'<font name="Courier">\1</font>', text)
        return text

    def para(text, x, y, w, size=10.1, leading=14, color=ink, bold=False, draw=True):
        style = ParagraphStyle("body", fontName="Helvetica-Bold" if bold else "Helvetica",
                               fontSize=size, leading=leading, textColor=color, spaceAfter=0)
        obj = Paragraph(rich(text), style)
        _, h = obj.wrap(w, 10000)
        if draw:
            obj.drawOn(c, x, y-h)
        return y-h

    def blocks(items, x, y, w, *, size=10.1, leading=14, draw=True):
        for block in items:
            if "p" in block:
                y = para(block["p"], x, y, w, size, leading, draw=draw) - 7
            elif "heading" in block:
                y -= 3
                y = para(block["heading"], x, y, w, size+1.2, leading+1, purple, True, draw) - 5
            elif "bullets" in block:
                for text in block["bullets"]:
                    if draw:
                        c.setFillColor(purple)
                        c.circle(x+2.5, y-5, 1.5, fill=1, stroke=0)
                    y = para(text, x+12, y, w-12, size, leading, draw=draw) - 6
                y -= 1
            elif "code" in block:
                lines = block["code"].splitlines()
                font_size = 8.7
                while max(c.stringWidth(line, "Courier", font_size) for line in lines) > w-18:
                    font_size -= 0.1
                assert font_size >= 7.8, "Code block would be too small"
                line_height = font_size * 1.4
                h = len(lines) * line_height + 16
                if draw:
                    c.setFillColor(pale)
                    c.roundRect(x, y-h, w, h, 5, fill=1, stroke=0)
                    c.setFillColor(ink)
                    c.setFont("Courier", font_size)
                    for i,line in enumerate(lines):
                        c.drawString(x+9, y-11-font_size-i*line_height, line)
                y -= h+8
            elif "table" in block:
                spec=block["table"]
                fractions=spec.get("widths") or [1/len(spec["headers"])]*len(spec["headers"])
                pstyle=ParagraphStyle("cell",fontName="Helvetica",fontSize=size-0.2,leading=leading-0.7,textColor=ink)
                hstyle=ParagraphStyle("head",parent=pstyle,fontName="Helvetica-Bold",textColor=colors.white)
                rows=[[Paragraph(rich(s),hstyle) for s in spec["headers"]]]
                rows.extend([[Paragraph(rich(s),pstyle) for s in row] for row in spec["rows"]])
                table=Table(rows,colWidths=[w*f for f in fractions])
                table.setStyle(TableStyle([
                    ("BACKGROUND",(0,0),(-1,0),purple),
                    ("ROWBACKGROUNDS",(0,1),(-1,-1),[colors.white,pale]),
                    ("VALIGN",(0,0),(-1,-1),"TOP"),
                    ("LEFTPADDING",(0,0),(-1,-1),8),("RIGHTPADDING",(0,0),(-1,-1),8),
                    ("TOPPADDING",(0,0),(-1,-1),6),("BOTTOMPADDING",(0,0),(-1,-1),6),
                    ("LINEBELOW",(0,-1),(-1,-1),0.4,colors.HexColor("#DDD7E9")),
                ]))
                _, h = table.wrap(w,10000)
                if draw: table.drawOn(c,x,y-h)
                y -= h+9
        return y

    def picture(spec,x,y,w=None,h=None,caption=True):
        reader=ImageReader(str(DOCS/spec["file"]))
        iw,ih=reader.getSize()
        if h is None: h=w*ih/iw
        if w is None: w=h*iw/ih
        c.drawImage(reader,x,y-h,width=w,height=h,mask='auto')
        c.setStrokeColor(colors.HexColor("#E0DDE7"))
        c.setLineWidth(0.4)
        c.rect(x,y-h,w,h,fill=0,stroke=1)
        bottom=y-h
        if caption:
            bottom=para(spec['caption'],x,bottom-5,w,size=8.2,leading=10.6,color=muted)-4
        return bottom

    for number,page in enumerate(data['pages'],1):
        c.bookmarkPage(str(number))
        c.addOutlineEntry(page['title'],str(number),0)
        c.setFillColor(colors.white); c.rect(0,0,width,height,fill=1,stroke=0)
        c.setFillColor(purple); c.rect(0,height-5*mm,width,5*mm,fill=1,stroke=0)
        c.setFont('Helvetica-Bold',9); c.setFillColor(purple)
        c.drawString(margin,height-12*mm,'texstage  /  USER MANUAL')
        c.setFont('Helvetica',8.5); c.setFillColor(muted)
        c.drawRightString(width-margin,height-12*mm,'0.2.1.dev0  |  October 2026')
        if page['layout']=='cover':
            para(page['title'],margin,height-24*mm,usable,size=32,leading=37,color=ink,bold=True)
            para(page['subtitle'],margin,height-40*mm,usable,size=17,leading=22,color=purple)
            para(page['blocks'][0]['p'],margin,height-53*mm,usable,size=12,leading=17)
            picture(page['images'][0],margin,height-72*mm,w=191*mm,caption=False)
            picture(page['images'][1],width-margin-46*mm,height-72*mm,h=108*mm,caption=False)
            para(page['blocks'][2]['p'],margin,24*mm,usable,size=8.5,leading=11,color=muted)
            bottom=15*mm
        else:
            c.setFont('Helvetica-Bold',22); c.setFillColor(ink)
            c.drawString(margin,height-25*mm,page['title'])
            y=height-33*mm
            if page['layout']=='text':
                bottom=blocks(page['blocks'],margin,y,usable,size=10,leading=13.7)
            elif page['layout']=='columns':
                iw=180*mm
                left=picture(page['images'][0],margin,y,iw)
                right=blocks(page['blocks'],margin+iw+8*mm,y,usable-iw-8*mm,size=9.6,leading=13.1)
                bottom=min(left,right)
            else:
                if page['layout']=='figure':
                    img=page['images'][0]
                    iw=215*mm
                    left=picture(img,margin+(usable-iw)/2,y,iw)
                    bottom=blocks(page['blocks'],margin,left-5,usable,size=10.1,leading=14)
                elif page['layout']=='gallery':
                    imgs=page['images']; ih=112*mm
                    widths=[ih*ImageReader(str(DOCS/im['file'])).getSize()[0]/ImageReader(str(DOCS/im['file'])).getSize()[1] for im in imgs]
                    gap=12*mm; total=sum(widths)+gap*(len(imgs)-1)
                    x=margin+(usable-total)/2; bottoms=[]
                    for im,iw in zip(imgs,widths):
                        bottoms.append(picture(im,x,y,w=iw,h=ih)); x+=iw+gap
                    bottom=blocks(page['blocks'],margin,min(bottoms)-5,usable,size=10.1,leading=14)
                elif page['layout']=='mixed':
                    phone,desk=page['images']
                    left=picture(phone,margin,y,h=104*mm)
                    right=picture(desk,margin+57*mm,y,w=usable-57*mm)
                    bottom=blocks(page['blocks'],margin,min(left,right)-5,usable,size=10.1,leading=14)
                else: raise ValueError(page['layout'])
        assert bottom >= 14*mm, f"Page {number} ({page['title']}) overflows: bottom {bottom/mm:.1f} mm"
        c.setStrokeColor(colors.HexColor('#DDD7E9')); c.line(margin,11*mm,width-margin,11*mm)
        c.setFont('Helvetica',8); c.setFillColor(muted)
        c.drawString(margin,7*mm,'Presenter and participant guide  |  Synthetic demonstration screens')
        c.drawRightString(width-margin,7*mm,f'{number:02d} / {len(data["pages"]):02d}')
        c.showPage()
        print(f"Rendered {number:02d}: {page['title']}")
    c.save()


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir',type=Path,default=DOCS)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    data=json.loads((DOCS/'manual-content.json').read_text(encoding='utf-8'))
    check_images(data)
    md=markdown(data)
    if args.check:
        assert (DOCS/'manual.md').read_text(encoding='utf-8')==md,'Regenerate manual.md'
        assert (DOCS/'manual.pdf').read_bytes().startswith(b'%PDF-'),'Missing manual.pdf'
        manifest=json.loads((DOCS/'manual-build.json').read_text(encoding='utf-8'))
        assert manifest == build_manifest(DOCS), 'Manual inputs or outputs changed; regenerate both formats'
        print('Manual Markdown, PDF build manifest and screenshot hashes are current')
        return
    args.output_dir.mkdir(parents=True,exist_ok=True)
    render_pdf(data,args.output_dir/'manual.pdf')
    (args.output_dir/'manual.md').write_text(md,encoding='utf-8',newline='\n')
    (args.output_dir/'manual-build.json').write_text(
        json.dumps(build_manifest(args.output_dir),indent=2)+'\n',encoding='utf-8',newline='\n')
    print(f'Wrote {args.output_dir / "manual.pdf"} and manual.md')


if __name__=='__main__':
    main()
