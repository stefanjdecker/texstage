"""Render the illustrated manual from docs/manual-content.json.

Requires Python, pdfLaTeX and latexmk. Writes Markdown, PDF and an independently compilable
LaTeX project under docs/manual-latex, using the same original screenshots.
--check verifies generated Markdown and screenshot hashes without changing files.
--output-dir writes the reading formats and screenshot assets elsewhere for a preview.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess

from manual_latex import latex
from reference_format import markdown as reference_markdown

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"


def slug(text):
    return re.sub(r"[^a-z0-9 -]", "", text.lower()).replace(" ", "-")


def markdown(data):
    lines = ["<!-- Generated by maintenance/build_manual.py from manual-content.json. -->",
             "# " + data["title"], "", "**" + data["subtitle"] + "**", "",
             "[Download the illustrated PDF](manual.pdf) | [LaTeX source](manual-latex/main.tex) "
             "| [LaTeX build instructions](manual-latex/README.md)", "", "## Contents", ""]
    lines += [f"- [{p['title']}](#{slug(p['title'])})" for p in data["pages"][1:]]
    for index, page in enumerate(data["pages"]):
        if index:
            lines += ["", "## " + page["title"], ""]
        for block in page["blocks"]:
            if "p" in block:
                lines += [block["p"], ""]
            elif "heading" in block:
                lines += ["### " + block["heading"], ""]
            elif "bullets" in block:
                lines += ["- " + line for line in block["bullets"]] + [""]
            elif "code" in block:
                lines += ["```", block["code"], "```", ""]
            elif "table" in block:
                table = block["table"]
                lines += ["| " + " | ".join(table["headers"]) + " |",
                          "| " + " | ".join("---" for _ in table["headers"]) + " |"]
                lines += ["| " + " | ".join(row) + " |" for row in table["rows"]]
                lines += [""]
        for picture in page["images"]:
            lines += [f"![{picture['caption']}]({picture['file']})", "", picture["caption"], ""]
    return "\n".join(lines).rstrip() + "\n"


def check_images(data):
    manifest = json.loads((DOCS / "images/manual/captures.json").read_text(encoding="utf-8"))
    hashes = {p["file"]: p["sha256"] for p in manifest["screenshots"]}
    used = {p["file"] for page in data["pages"] for p in page["images"]}
    assert used == set(hashes), "Manual images and capture inventory differ"
    for filename in used:
        path = (DOCS / filename).resolve()
        assert path.is_relative_to(DOCS.resolve())
        assert hashlib.sha256(path.read_bytes()).hexdigest() == hashes[filename], filename


def build_manifest(output_dir):
    inputs = ["docs/manual-content.json", "docs/images/manual/captures.json",
              "maintenance/build_manual.py", "maintenance/manual_latex.py",
              "docs/manual-latex/manual.sty", "maintenance/reference_format.py",
              "docs/latex-reference-inventory.json"]
    return {
        "schema_version": 1,
        "inputs": {name: hashlib.sha256((ROOT/name).read_bytes()).hexdigest() for name in inputs},
        "outputs": {name: hashlib.sha256((output_dir/name).read_bytes()).hexdigest()
                    for name in ("manual.md", "manual.pdf", "manual-latex/main.tex", "latex-reference.md")},
    }


def render_pdf(target):
    project=target.parent/"manual-latex"
    output=(ROOT/".manual-build/article" if target.parent.resolve()==DOCS.resolve()
            else target.parent/".latex-build").resolve()
    output.mkdir(parents=True,exist_ok=True)
    subprocess.run(["latexmk","-pdf","-interaction=nonstopmode","-halt-on-error",
                    "-no-shell-escape",r"-usepretex=\def\manualdocroot{}",
                    "-outdir="+str(output),"main.tex"],
                   cwd=project,check=True)
    log=(output/"main.log").read_text(encoding="utf-8",errors="replace")
    assert "Overfull" not in log,"Manual layout overflow; inspect the LaTeX log"
    shutil.copyfile(output/"main.pdf",target)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir',type=Path,default=DOCS)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    data=json.loads((DOCS/'manual-content.json').read_text(encoding='utf-8'))
    check_images(data)
    md=markdown(data)
    tex=latex(data)
    reference=dict(data, title="texstage LaTeX authoring and command reference",
                   subtitle="Packages, commands, options and developer interfaces",
                   pages=[p for p in data["pages"] if p.get("reference")])
    ref_md=reference_markdown(reference)
    if args.check:
        assert (DOCS/"latex-reference.md").read_text(encoding="utf-8")==ref_md, "Regenerate reference"
        assert (DOCS/'manual.md').read_text(encoding='utf-8')==md,'Regenerate manual.md'
        assert (DOCS/'manual-latex/main.tex').read_text(encoding='utf-8')==tex,'Regenerate LaTeX source'
        assert (DOCS/'manual.pdf').read_bytes().startswith(b'%PDF-'),'Missing manual.pdf'
        manifest=json.loads((DOCS/'manual-build.json').read_text(encoding='utf-8'))
        assert manifest == build_manifest(DOCS), 'Manual inputs or outputs changed; regenerate both formats'
        print('Manual Markdown, LaTeX, PDF build manifest and screenshot hashes are current')
        return
    args.output_dir.mkdir(parents=True,exist_ok=True)
    project=args.output_dir/'manual-latex'
    project.mkdir(parents=True,exist_ok=True)
    (project/'main.tex').write_text(tex,encoding='utf-8',newline='\n')
    if args.output_dir.resolve()!=DOCS.resolve():
        for name in ('manual.sty','README.md'):
            shutil.copyfile(DOCS/'manual-latex'/name,project/name)
        shutil.copytree(DOCS/'images/manual',args.output_dir/'images/manual',dirs_exist_ok=True)
    render_pdf(args.output_dir/'manual.pdf')
    (args.output_dir/'latex-reference.md').write_text(ref_md,encoding='utf-8',newline='\n')
    (args.output_dir/'manual.md').write_text(md,encoding='utf-8',newline='\n')
    (args.output_dir/'manual-build.json').write_text(
        json.dumps(build_manifest(args.output_dir),indent=2)+'\n',encoding='utf-8',newline='\n')
    print(f'Wrote {args.output_dir / "manual.pdf"}, manual.md and manual-latex/main.tex')


if __name__=='__main__':
    main()
